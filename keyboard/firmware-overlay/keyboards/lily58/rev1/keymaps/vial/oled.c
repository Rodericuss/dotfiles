enum last_key_icon {
    LAST_KEY_TEXT,
    LAST_KEY_ENTER,
    LAST_KEY_ESC,
    LAST_KEY_LEFT,
    LAST_KEY_RIGHT,
    LAST_KEY_UP,
    LAST_KEY_DOWN,
};

static char last_key_name[16] = "READY";
static enum last_key_icon last_key_visual = LAST_KEY_TEXT;
static bool last_key_dirty = true;

typedef struct {
    uint8_t visual;
    char name[16];
} last_key_sync_t;

static void set_last_key_name(uint16_t keycode) {
    last_key_visual = LAST_KEY_TEXT;
    if (keycode >= KC_A && keycode <= KC_Z) {
        last_key_name[0] = 'A' + (keycode - KC_A);
        last_key_name[1] = '\0';
        return;
    }
    if (keycode >= KC_1 && keycode <= KC_0) {
        last_key_name[0] = (keycode == KC_0) ? '0' : '1' + (keycode - KC_1);
        last_key_name[1] = '\0';
        return;
    }

    switch (keycode) {
        case KC_ENT:  last_key_visual = LAST_KEY_ENTER; break;
        case KC_ESC:  last_key_visual = LAST_KEY_ESC; break;
        case KC_TAB:  snprintf(last_key_name, sizeof(last_key_name), "TAB"); break;
        case KC_BSPC: snprintf(last_key_name, sizeof(last_key_name), "BKSP"); break;
        case KC_SPC:  snprintf(last_key_name, sizeof(last_key_name), "SPACE"); break;
        case KC_LEFT: last_key_visual = LAST_KEY_LEFT; break;
        case KC_RGHT: last_key_visual = LAST_KEY_RIGHT; break;
        case KC_UP:   last_key_visual = LAST_KEY_UP; break;
        case KC_DOWN: last_key_visual = LAST_KEY_DOWN; break;
        case KC_LSFT:
        case KC_RSFT: snprintf(last_key_name, sizeof(last_key_name), "SHIFT"); break;
        case KC_LCTL:
        case KC_RCTL: snprintf(last_key_name, sizeof(last_key_name), "CTRL"); break;
        case KC_LALT:
        case KC_RALT: snprintf(last_key_name, sizeof(last_key_name), "ALT"); break;
        case KC_LGUI:
        case KC_RGUI: snprintf(last_key_name, sizeof(last_key_name), "GUI"); break;
        case KC_MINS: snprintf(last_key_name, sizeof(last_key_name), "-"); break;
        case KC_EQL:  snprintf(last_key_name, sizeof(last_key_name), "="); break;
        case KC_COMM: snprintf(last_key_name, sizeof(last_key_name), ","); break;
        case KC_DOT:  snprintf(last_key_name, sizeof(last_key_name), "."); break;
        case KC_SLSH: snprintf(last_key_name, sizeof(last_key_name), "/"); break;
        case KC_SCLN: snprintf(last_key_name, sizeof(last_key_name), ";"); break;
        case KC_QUOT: snprintf(last_key_name, sizeof(last_key_name), "'"); break;
        case KC_LBRC: snprintf(last_key_name, sizeof(last_key_name), "["); break;
        case KC_RBRC: snprintf(last_key_name, sizeof(last_key_name), "]"); break;
        case KC_BSLS: snprintf(last_key_name, sizeof(last_key_name), "\\"); break;
        case KC_GRV:  snprintf(last_key_name, sizeof(last_key_name), "`"); break;
        default:      snprintf(last_key_name, sizeof(last_key_name), "0x%04X", keycode); break;
    }
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (record->event.pressed) {
        set_last_key_name(keycode);
        last_key_dirty = true;
    }
    return true;
}

static void last_key_sync_slave_handler(uint8_t in_buflen, const void *in_data, uint8_t out_buflen, void *out_data) {
    const last_key_sync_t *incoming = (const last_key_sync_t *)in_data;
    last_key_visual = (enum last_key_icon)incoming->visual;
    memcpy(last_key_name, incoming->name, sizeof(last_key_name));
    last_key_name[sizeof(last_key_name) - 1] = '\0';
    last_key_dirty = true;
}

void keyboard_post_init_user(void) {
    transaction_register_rpc(LAST_KEY_SYNC, last_key_sync_slave_handler);
}

void housekeeping_task_user(void) {
    if (is_keyboard_master()) {
        static uint32_t last_sync;
        if (timer_elapsed32(last_sync) > 50) {
            last_key_sync_t outgoing = {
                .visual = (uint8_t)last_key_visual,
            };
            memcpy(outgoing.name, last_key_name, sizeof(outgoing.name));
            transaction_rpc_send(LAST_KEY_SYNC, sizeof(outgoing), &outgoing);
            last_sync = timer_read32();
        }
    }
}

