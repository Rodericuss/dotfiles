static void draw_last_key_text(void) {
    uint8_t length = strlen(last_key_name);
    // A single key should use almost the entire layer-art area. Because the
    // OLED is rotated 270 degrees, the logical 32px width is the physical
    // 16px height; scale 6 fills that height without clipping.
    uint8_t scale = (length == 1) ? 6 : (length == 2) ? 2 : 1;
    uint8_t glyph_width = 5 * scale;
    uint8_t spacing = scale;
    uint8_t total_width = length ? (length * (glyph_width + spacing) - spacing) : 0;
    uint8_t x = (32 - total_width) / 2;
    uint8_t y = 64 + (64 - (7 * scale)) / 2;

    for (uint8_t i = 0; i < length; i++) {
        uint8_t glyph_index = 0xFF;
        for (uint8_t j = 0; j < sizeof(last_key_font_chars) - 1; j++) {
            if (pgm_read_byte(&last_key_font_chars[j]) == last_key_name[i]) {
                glyph_index = j;
                break;
            }
        }
        if (glyph_index != 0xFF) {
            for (uint8_t column = 0; column < 5; column++) {
                uint8_t bits = pgm_read_byte(&last_key_font[glyph_index][column]);
                for (uint8_t row = 0; row < 7; row++) {
                    if (bits & (1 << row)) {
                        for (uint8_t dx = 0; dx < scale; dx++) {
                            for (uint8_t dy = 0; dy < scale; dy++) {
                                oled_write_pixel(x + column * scale + dx, y + row * scale + dy, true);
                            }
                        }
                    }
                }
            }
        }
        x += glyph_width + spacing;
    }
}

static void render_last_key(void) {
    if (!last_key_dirty) {
        return;
    }

    // With OLED_ROTATION_270 this is the logical 32x64 region that becomes
    // the physical 128x16 area previously used by the large layer bitmap.
    for (uint8_t y = 64; y < 128; y++) {
        for (uint8_t x = 0; x < 32; x++) {
            oled_write_pixel(x, y, false);
        }
    }

    if (last_key_visual != LAST_KEY_TEXT) {
        const uint8_t x0 = 8;
        const uint8_t y0 = 88;

        switch (last_key_visual) {
            case LAST_KEY_LEFT:
                for (uint8_t x = x0 + 2; x < x0 + 16; x++) oled_write_pixel(x, y0 + 8, true);
                for (uint8_t i = 0; i < 7; i++) {
                    oled_write_pixel(x0 + 2 + i, y0 + 8 - i, true);
                    oled_write_pixel(x0 + 2 + i, y0 + 8 + i, true);
                }
                break;
            case LAST_KEY_RIGHT:
                for (uint8_t x = x0 + 2; x < x0 + 16; x++) oled_write_pixel(x, y0 + 8, true);
                for (uint8_t i = 0; i < 7; i++) {
                    oled_write_pixel(x0 + 15 - i, y0 + 8 - i, true);
                    oled_write_pixel(x0 + 15 - i, y0 + 8 + i, true);
                }
                break;
            case LAST_KEY_UP:
                for (uint8_t y = y0 + 2; y < y0 + 16; y++) oled_write_pixel(x0 + 8, y, true);
                for (uint8_t i = 0; i < 7; i++) {
                    oled_write_pixel(x0 + 8 - i, y0 + 2 + i, true);
                    oled_write_pixel(x0 + 8 + i, y0 + 2 + i, true);
                }
                break;
            case LAST_KEY_DOWN:
                for (uint8_t y = y0 + 2; y < y0 + 16; y++) oled_write_pixel(x0 + 8, y, true);
                for (uint8_t i = 0; i < 7; i++) {
                    oled_write_pixel(x0 + 8 - i, y0 + 15 - i, true);
                    oled_write_pixel(x0 + 8 + i, y0 + 15 - i, true);
                }
                break;
            case LAST_KEY_ENTER:
                for (uint8_t x = x0 + 2; x < x0 + 16; x++) oled_write_pixel(x, y0 + 4, true);
                for (uint8_t y = y0 + 4; y < y0 + 13; y++) oled_write_pixel(x0 + 2, y, true);
                for (uint8_t x = x0 + 2; x < x0 + 13; x++) oled_write_pixel(x, y0 + 13, true);
                for (uint8_t i = 0; i < 5; i++) {
                    oled_write_pixel(x0 + 2 + i, y0 + 13 - i, true);
                    oled_write_pixel(x0 + 2 + i, y0 + 13 + i, true);
                }
                break;
            case LAST_KEY_ESC:
                for (uint8_t x = x0 + 2; x < x0 + 15; x++) {
                    oled_write_pixel(x, y0 + 3, true);
                    oled_write_pixel(x, y0 + 13, true);
                }
                for (uint8_t y = y0 + 3; y <= y0 + 13; y++) {
                    oled_write_pixel(x0 + 2, y, true);
                    oled_write_pixel(x0 + 14, y, true);
                }
                break;
            case LAST_KEY_TEXT:
                break;
        }
    } else {
        draw_last_key_text();
    }

    last_key_dirty = false;
}

